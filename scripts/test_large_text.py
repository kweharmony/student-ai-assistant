def estimate_tokens(text: str) -> int:
    """Приблизительная оценка количества токенов (1 токен ≈ 4 символа для русского)"""
    return len(text) // 4


def print_stats(text: str, title: str = "СТАТИСТИКА ТЕКСТА"):
    """Вывод статистики по тексту"""
    print(f"\n{'=' * 60}")
    print(f"{title:^60}")
    print(f"{'=' * 60}")
    print(f"📊 Символов: {len(text):,}")
    print(f"📊 Слов (приблизительно): {len(text.split()):,}")
    print(f"📊 Строк: {text.count(chr(10)) + 1:,}")
    print(f"📊 Токенов (оценка): ~{estimate_tokens(text):,}")
    print(f"{'=' * 60}\n")


